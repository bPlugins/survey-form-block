<?php
/**
 * Premium gate for Survey Form Block.
 *
 * One source of truth for "may the premium design tools run", backed by Freemius
 * (`bpsvb_fs()`), plus the plumbing that publishes that flag to the editor and to
 * the frontend renderer.
 *
 * The design system degrades rather than breaks: attributes saved while Pro was
 * active are preserved verbatim, and `resolveDesign()` on the JS side falls each
 * Pro-only value back to its closest free equivalent.
 */

if ( ! defined( 'ABSPATH' ) ) { exit; }

if ( ! class_exists( 'BPSVB_Pro' ) ) {
	/**
	 * BPSVB_Pro class.
	 */
	class BPSVB_Pro {

		/**
		 * Public product page, used as the upgrade destination in the editor.
		 */
		const PRICING_URL = 'https://bplugins.com/products/survey-form-block';

		/** Script handle of the premium design presets (build/pro/design.js). */
		const DESIGN_HANDLE = 'svb-pro-design';

		/** Handles generated by register_block_type() from block.json. */
		const BLOCK_SCRIPTS = [ 'svb-survey-block-view-script', 'svb-survey-block-editor-script' ];
		const BLOCK_STYLE   = 'svb-survey-block-style';

		public function __construct() {
			// After the block is registered on init (priority 10), so its handles exist.
			add_action( 'init', [ $this, 'registerDesignBundle' ], 20 );

			// Runs late so the block's generated script handles already exist.
			add_action( 'enqueue_block_assets', [ $this, 'injectPremiumFlag' ], 20 );
		}

		/**
		 * Loads the premium design presets alongside the block.
		 *
		 * build/pro/ is @fs_premium_only, so the free WordPress.org build does not
		 * contain it and this returns early. In the premium build the script
		 * becomes a dependency of the block's editor and view scripts, so its
		 * hooks are in place before anything renders, and its stylesheet is
		 * printed straight after the block's own, wherever that loads.
		 *
		 * @return void
		 */
		public function registerDesignBundle() {
			$script = BPSVB_PATH . 'build/pro/design.js';
			$asset  = BPSVB_PATH . 'build/pro/design.asset.php';

			if ( ! BPSVB_HAS_PRO || ! file_exists( $script ) || ! file_exists( $asset ) ) {
				return;
			}

			$info = include $asset;

			wp_register_script(
				self::DESIGN_HANDLE,
				BPSVB_DIR . 'build/pro/design.js',
				isset( $info['dependencies'] ) ? $info['dependencies'] : [ 'wp-hooks' ],
				isset( $info['version'] ) ? $info['version'] : BPSVB_PLUGIN_VERSION,
				[ 'in_footer' => true ]
			);
			wp_set_script_translations( self::DESIGN_HANDLE, 'survey-form-block', BPSVB_PATH . 'languages' );

			foreach ( self::BLOCK_SCRIPTS as $handle ) {
				$registered = wp_scripts()->query( $handle, 'registered' );

				if ( $registered && ! in_array( self::DESIGN_HANDLE, $registered->deps, true ) ) {
					$registered->deps[] = self::DESIGN_HANDLE;
				}
			}

			// Inline after the block stylesheet rather than as its own file: the
			// premium rules must come after the free ones, and the block's style
			// prints in the editor, on classic themes and per block on block
			// themes alike.
			$css = BPSVB_PATH . 'build/pro/design.css';

			if ( file_exists( $css ) && wp_style_is( self::BLOCK_STYLE, 'registered' ) ) {
				wp_add_inline_style( self::BLOCK_STYLE, (string) file_get_contents( $css ) ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- local build file.
			}
		}

		/**
		 * Whether the premium feature set may be used.
		 *
		 * @return bool
		 */
		public static function isPremium() {
			$isPremium = false;

			if ( defined( 'BPSVB_HAS_PRO' ) && BPSVB_HAS_PRO && function_exists( 'bpsvb_fs' ) && bpsvb_fs() ) {
				$isPremium = (bool) bpsvb_fs()->can_use_premium_code();
			}

			/**
			 * Final say on whether the premium design tools may run.
			 *
			 * Filtered in both directions on purpose: a bundle can unlock Pro
			 * without the premium SDK, and a developer with the premium SDK
			 * vendored locally can force the free experience to check it.
			 *
			 * @param bool $isPremium
			 */
			return (bool) apply_filters( 'svb_is_premium', $isPremium );
		}

		/**
		 * URL the editor's "Get Pro" buttons point at.
		 *
		 * @return string
		 */
		public static function pricingUrl() {
			$url = self::PRICING_URL;

			if ( defined( 'BPSVB_DASHBOARD_SLUG' ) && ! self::isPremium() ) {
				$url = admin_url( 'admin.php?page=' . BPSVB_DASHBOARD_SLUG . '#/pricing' );
			}

			return (string) apply_filters( 'svb_pricing_url', $url );
		}

		/**
		 * Publishes the premium flag to the editor and the frontend renderer.
		 *
		 * The frontend needs it too: `view.js` re-renders the survey with React and
		 * has to know whether Pro-only styling may be applied.
		 *
		 * @return void
		 */
		public function injectPremiumFlag() {
			$data = sprintf(
				'var svbIsPremium = %s; var svbPricingUrl = %s;',
				wp_json_encode( self::isPremium() ),
				wp_json_encode( self::pricingUrl() )
			);

			foreach ( [ 'svb-survey-block-view-script', 'svb-survey-block-editor-script' ] as $handle ) {
				if ( wp_script_is( $handle, 'registered' ) ) {
					wp_add_inline_script( $handle, $data, 'before' );
				}
			}
		}
	}

	new BPSVB_Pro();
}
